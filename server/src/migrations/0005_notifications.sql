-- Notifications: the in-app list (bell) plus a push queue for the mobile apps.
--
-- * notifications  one row per message for one user (buyer or seller). Written in the same
--                  transaction as the order change that caused it, so they never disagree.
--                  Rows older than 90 days are deleted by the janitor.
-- * push_devices   phones that may receive push notifications (Firebase Cloud Messaging tokens).
--                  A token belongs to one user at a time: signing in as someone else on the same
--                  phone moves it.
-- * push_outbox    one row per (notification, device) still to be pushed. A worker claims rows with
--                  FOR UPDATE SKIP LOCKED and a lease (locked_until), so several server instances
--                  never push the same row twice. Failed pushes retry with backoff.

CREATE TABLE notifications (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind        TEXT    NOT NULL,
    title       TEXT    NOT NULL,
    body        TEXT    NOT NULL,
    link        TEXT,
    read_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by  BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by  BIGINT  REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_notifications_user ON notifications (user_id, id DESC);
CREATE INDEX idx_notifications_unread ON notifications (user_id) WHERE read_at IS NULL;
CREATE INDEX idx_notifications_created ON notifications (created_at);
CREATE TRIGGER stamp_audit BEFORE INSERT OR UPDATE ON notifications FOR EACH ROW EXECUTE FUNCTION stamp_audit();

CREATE TABLE push_devices (
    id            BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token         TEXT    NOT NULL UNIQUE,
    platform      TEXT    NOT NULL CHECK (platform IN ('android', 'ios', 'web')),
    last_seen_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by    BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by    BIGINT  REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_push_devices_user ON push_devices (user_id);
CREATE TRIGGER stamp_audit BEFORE INSERT OR UPDATE ON push_devices FOR EACH ROW EXECUTE FUNCTION stamp_audit();

CREATE TABLE push_outbox (
    id               BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id  BIGINT  NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
    device_id        BIGINT  NOT NULL REFERENCES push_devices(id) ON DELETE CASCADE,
    status           TEXT    NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'failed', 'skipped')),
    attempts         INTEGER NOT NULL DEFAULT 0,
    next_attempt_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_until     TIMESTAMPTZ,
    last_error       TEXT,
    sent_at          TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by       BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by       BIGINT  REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_push_outbox_due ON push_outbox (next_attempt_at) WHERE status = 'pending';
CREATE INDEX idx_push_outbox_notification ON push_outbox (notification_id);
CREATE INDEX idx_push_outbox_device ON push_outbox (device_id);
CREATE TRIGGER stamp_audit BEFORE INSERT OR UPDATE ON push_outbox FOR EACH ROW EXECUTE FUNCTION stamp_audit();

