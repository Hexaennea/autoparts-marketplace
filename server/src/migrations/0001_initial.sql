-- PartPilot initial schema (PostgreSQL).
-- Conventions: identity primary keys, money in paise (BIGINT), timestamps TIMESTAMPTZ (UTC),
-- enums enforced with CHECK constraints, every foreign key indexed.

CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;

-- unaccent() is not IMMUTABLE, so wrap it for use in generated columns and indexes.
CREATE OR REPLACE FUNCTION pp_unaccent(text) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
    AS $$ SELECT public.unaccent('public.unaccent'::regdictionary, $1) $$;

CREATE TABLE users (
    id              BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           TEXT    NOT NULL,
    password_hash   TEXT    NOT NULL,
    full_name       TEXT    NOT NULL,
    phone           TEXT,
    role            TEXT    NOT NULL DEFAULT 'buyer' CHECK (role IN ('buyer', 'seller', 'admin')),
    status          TEXT    NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    failed_logins   INTEGER NOT NULL DEFAULT 0,
    locked_until    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (email = lower(email))
);
CREATE UNIQUE INDEX users_email_key ON users (email);
CREATE INDEX idx_users_role ON users (role);

CREATE TABLE sessions (
    id            BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash    TEXT    NOT NULL UNIQUE,
    csrf_token    TEXT    NOT NULL,
    user_id       BIGINT  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at    TIMESTAMPTZ NOT NULL,
    ip            TEXT,
    user_agent    TEXT
);
CREATE INDEX idx_sessions_user ON sessions(user_id);
CREATE INDEX idx_sessions_expires ON sessions(expires_at);

CREATE TABLE sellers (
    id                 BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT  NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    business_name      TEXT    NOT NULL,
    display_name       TEXT    NOT NULL,
    gstin              TEXT    NOT NULL UNIQUE,
    pan                TEXT    NOT NULL,
    phone              TEXT    NOT NULL,
    address_line       TEXT    NOT NULL,
    city               TEXT    NOT NULL,
    state              TEXT    NOT NULL,
    pincode            TEXT    NOT NULL,
    bank_account_name  TEXT    NOT NULL,
    bank_account_last4 TEXT    NOT NULL,
    bank_ifsc          TEXT    NOT NULL,
    kyc_status         TEXT    NOT NULL DEFAULT 'pending'
                       CHECK (kyc_status IN ('pending', 'approved', 'rejected', 'suspended')),
    kyc_note           TEXT,
    rating_avg         DOUBLE PRECISION NOT NULL DEFAULT 0,
    rating_count       INTEGER NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at        TIMESTAMPTZ
);
CREATE INDEX idx_sellers_kyc ON sellers(kyc_status);

CREATE TABLE addresses (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    full_name   TEXT    NOT NULL,
    phone       TEXT    NOT NULL,
    line1       TEXT    NOT NULL,
    line2       TEXT,
    landmark    TEXT,
    city        TEXT    NOT NULL,
    state       TEXT    NOT NULL,
    pincode     TEXT    NOT NULL,
    is_default  BOOLEAN NOT NULL DEFAULT false,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_addresses_user ON addresses(user_id);

-- Vehicle master data (owned by admins). A variant is one buyable configuration over a year range.
CREATE TABLE makes (
    id         BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT    NOT NULL UNIQUE,
    slug       TEXT    NOT NULL UNIQUE,
    country    TEXT,
    is_active  BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE models (
    id         BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    make_id    BIGINT  NOT NULL REFERENCES makes(id) ON DELETE RESTRICT,
    name       TEXT    NOT NULL,
    slug       TEXT    NOT NULL,
    body_type  TEXT    NOT NULL DEFAULT 'hatchback'
               CHECK (body_type IN ('hatchback', 'sedan', 'suv', 'muv', 'pickup', 'coupe', 'van')),
    is_active  BOOLEAN NOT NULL DEFAULT true,
    UNIQUE (make_id, slug)
);
CREATE INDEX idx_models_make ON models(make_id);

CREATE TABLE variants (
    id            BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id      BIGINT  NOT NULL REFERENCES models(id) ON DELETE RESTRICT,
    code          TEXT    NOT NULL UNIQUE,
    name          TEXT    NOT NULL,
    generation    TEXT,
    year_from     INTEGER NOT NULL CHECK (year_from BETWEEN 1950 AND 2100),
    year_to       INTEGER CHECK (year_to IS NULL OR year_to >= year_from),
    fuel          TEXT    NOT NULL CHECK (fuel IN ('petrol', 'diesel', 'cng', 'electric', 'hybrid')),
    transmission  TEXT    NOT NULL CHECK (transmission IN ('manual', 'automatic', 'amt', 'cvt', 'dct')),
    engine_cc     INTEGER,
    engine_code   TEXT,
    is_active     BOOLEAN NOT NULL DEFAULT true
);
CREATE INDEX idx_variants_model ON variants(model_id);

CREATE TABLE categories (
    id         BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id  BIGINT  REFERENCES categories(id) ON DELETE RESTRICT,
    name       TEXT    NOT NULL,
    slug       TEXT    NOT NULL UNIQUE,
    icon       TEXT    NOT NULL DEFAULT 'box',
    position   INTEGER NOT NULL DEFAULT 0,
    is_active  BOOLEAN NOT NULL DEFAULT true
);
CREATE INDEX idx_categories_parent ON categories(parent_id);

CREATE TABLE brands (
    id        BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      TEXT    NOT NULL UNIQUE,
    slug      TEXT    NOT NULL UNIQUE,
    is_oem    BOOLEAN NOT NULL DEFAULT false,
    is_active BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE products (
    id               BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id        BIGINT  NOT NULL REFERENCES sellers(id) ON DELETE RESTRICT,
    sku              TEXT    NOT NULL,
    title            TEXT    NOT NULL,
    slug             TEXT    NOT NULL,
    description      TEXT    NOT NULL DEFAULT '',
    category_id      BIGINT  NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    brand_id         BIGINT  NOT NULL REFERENCES brands(id) ON DELETE RESTRICT,
    part_number      TEXT    NOT NULL,
    condition        TEXT    NOT NULL DEFAULT 'new' CHECK (condition IN ('new', 'oem_genuine')),
    price_paise      BIGINT  NOT NULL CHECK (price_paise > 0),
    mrp_paise        BIGINT  NOT NULL CHECK (mrp_paise >= price_paise),
    stock            INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    gst_rate_bps     INTEGER NOT NULL DEFAULT 1800 CHECK (gst_rate_bps IN (0, 500, 1200, 1800, 2800)),
    hsn_code         TEXT    NOT NULL DEFAULT '8708',
    warranty_months  INTEGER NOT NULL DEFAULT 0 CHECK (warranty_months BETWEEN 0 AND 120),
    weight_grams     INTEGER NOT NULL DEFAULT 500 CHECK (weight_grams > 0),
    is_universal     BOOLEAN NOT NULL DEFAULT false,
    status           TEXT    NOT NULL DEFAULT 'draft'
                     CHECK (status IN ('draft', 'pending', 'active', 'rejected', 'archived')),
    moderation_note  TEXT,
    rating_avg       DOUBLE PRECISION NOT NULL DEFAULT 0,
    rating_count     INTEGER NOT NULL DEFAULT 0,
    sold_count       INTEGER NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (seller_id, sku)
);
CREATE INDEX idx_products_seller ON products(seller_id);
CREATE INDEX idx_products_category ON products(category_id);
CREATE INDEX idx_products_brand ON products(brand_id);
CREATE INDEX idx_products_status ON products(status);

-- Normalised part numbers (the listing's own number plus OEM cross-references) for exact lookup.
CREATE TABLE product_part_numbers (
    product_id   BIGINT  NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    number       TEXT    NOT NULL,
    number_norm  TEXT    NOT NULL,
    kind         TEXT    NOT NULL CHECK (kind IN ('primary', 'oem', 'cross')),
    PRIMARY KEY (product_id, number_norm)
);
CREATE INDEX idx_part_numbers_norm ON product_part_numbers(number_norm text_pattern_ops);

CREATE TABLE product_fitments (
    product_id  BIGINT  NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    variant_id  BIGINT  NOT NULL REFERENCES variants(id) ON DELETE RESTRICT,
    note        TEXT,
    PRIMARY KEY (product_id, variant_id)
);
CREATE INDEX idx_fitments_variant ON product_fitments(variant_id);

CREATE TABLE product_specs (
    product_id  BIGINT  NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    position    INTEGER NOT NULL,
    label       TEXT    NOT NULL,
    value       TEXT    NOT NULL,
    PRIMARY KEY (product_id, position)
);

CREATE TABLE media (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id   BIGINT  NOT NULL REFERENCES sellers(id) ON DELETE CASCADE,
    product_id  BIGINT  REFERENCES products(id) ON DELETE SET NULL,
    path        TEXT    NOT NULL UNIQUE,
    thumb_path  TEXT    NOT NULL,
    width       INTEGER NOT NULL,
    height      INTEGER NOT NULL,
    position    INTEGER NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_media_product ON media(product_id);
CREATE INDEX idx_media_seller ON media(seller_id);

-- Full-text search document per product (replaces SQLite FTS5). Kept in sync by the
-- listings service whenever a product, its brand/category or its part numbers change.
CREATE TABLE product_search (
    product_id    BIGINT PRIMARY KEY REFERENCES products(id) ON DELETE CASCADE,
    title         TEXT   NOT NULL DEFAULT '',
    brand         TEXT   NOT NULL DEFAULT '',
    category      TEXT   NOT NULL DEFAULT '',
    part_numbers  TEXT   NOT NULL DEFAULT '',
    description   TEXT   NOT NULL DEFAULT '',
    document      TSVECTOR GENERATED ALWAYS AS (
        setweight(to_tsvector('simple', pp_unaccent(coalesce(title, ''))), 'A') ||
        setweight(to_tsvector('simple', pp_unaccent(coalesce(brand, ''))), 'A') ||
        setweight(to_tsvector('simple', coalesce(part_numbers, '')), 'A') ||
        setweight(to_tsvector('simple', pp_unaccent(coalesce(category, ''))), 'B') ||
        setweight(to_tsvector('simple', pp_unaccent(coalesce(description, ''))), 'C')
    ) STORED
);
CREATE INDEX idx_product_search_document ON product_search USING GIN (document);
CREATE INDEX idx_product_search_title_trgm ON product_search USING GIN (title gin_trgm_ops);

CREATE TABLE garage_vehicles (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    variant_id  BIGINT  NOT NULL REFERENCES variants(id) ON DELETE RESTRICT,
    year        INTEGER NOT NULL,
    nickname    TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, variant_id, year)
);
CREATE INDEX idx_garage_variant ON garage_vehicles(variant_id);

CREATE TABLE cart_items (
    user_id     BIGINT  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id  BIGINT  NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    quantity    INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 20),
    added_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, product_id)
);
CREATE INDEX idx_cart_product ON cart_items(product_id);

CREATE TABLE wishlist_items (
    user_id     BIGINT  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id  BIGINT  NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    added_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, product_id)
);
CREATE INDEX idx_wishlist_product ON wishlist_items(product_id);

CREATE TABLE payouts (
    id               BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id        BIGINT  NOT NULL REFERENCES sellers(id) ON DELETE RESTRICT,
    reference        TEXT    NOT NULL UNIQUE,
    gross_paise      BIGINT  NOT NULL,
    commission_paise BIGINT  NOT NULL,
    tcs_paise        BIGINT  NOT NULL,
    refund_paise     BIGINT  NOT NULL,
    net_paise        BIGINT  NOT NULL,
    fulfilment_count INTEGER NOT NULL,
    created_by       BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_payouts_seller ON payouts(seller_id);
CREATE INDEX idx_payouts_created_by ON payouts(created_by);

CREATE TABLE orders (
    id                BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number            TEXT    NOT NULL UNIQUE,
    buyer_id          BIGINT  NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    idempotency_key   TEXT    NOT NULL,
    ship_name         TEXT    NOT NULL,
    ship_phone        TEXT    NOT NULL,
    ship_line1        TEXT    NOT NULL,
    ship_line2        TEXT,
    ship_landmark     TEXT,
    ship_city         TEXT    NOT NULL,
    ship_state        TEXT    NOT NULL,
    ship_pincode      TEXT    NOT NULL,
    vehicle_label     TEXT,
    items_paise       BIGINT  NOT NULL,
    shipping_paise    BIGINT  NOT NULL,
    total_paise       BIGINT  NOT NULL,
    gst_paise         BIGINT  NOT NULL,
    payment_method    TEXT    NOT NULL CHECK (payment_method IN ('cod', 'online')),
    payment_status    TEXT    NOT NULL CHECK (payment_status IN ('pending', 'paid', 'failed', 'refunded', 'partially_refunded', 'cod_due', 'cod_collected')),
    payment_ref       TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (buyer_id, idempotency_key)
);
CREATE INDEX idx_orders_buyer ON orders(buyer_id);
CREATE INDEX idx_orders_created ON orders(created_at);
CREATE INDEX idx_orders_payment_status ON orders(payment_status, created_at);

-- One fulfilment per seller per order. Sellers only ever see their own fulfilments.
CREATE TABLE fulfilments (
    id                BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          BIGINT  NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    seller_id         BIGINT  NOT NULL REFERENCES sellers(id) ON DELETE RESTRICT,
    status            TEXT    NOT NULL CHECK (status IN (
                          'pending_payment', 'placed', 'packed', 'shipped', 'delivered',
                          'cancelled', 'return_requested', 'returned')),
    items_paise       BIGINT  NOT NULL,
    shipping_paise    BIGINT  NOT NULL,
    commission_bps    INTEGER NOT NULL,
    commission_paise  BIGINT  NOT NULL,
    tcs_paise         BIGINT  NOT NULL,
    carrier           TEXT,
    tracking_number   TEXT,
    cancel_reason     TEXT,
    return_reason     TEXT,
    refund_paise      BIGINT  NOT NULL DEFAULT 0,
    payout_id         BIGINT  REFERENCES payouts(id) ON DELETE SET NULL,
    shipped_at        TIMESTAMPTZ,
    delivered_at      TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (order_id, seller_id)
);
CREATE INDEX idx_fulfilments_seller ON fulfilments(seller_id, status);
CREATE INDEX idx_fulfilments_order ON fulfilments(order_id);
CREATE INDEX idx_fulfilments_payout ON fulfilments(payout_id);

CREATE TABLE order_items (
    id               BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fulfilment_id    BIGINT  NOT NULL REFERENCES fulfilments(id) ON DELETE CASCADE,
    product_id       BIGINT  NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    title            TEXT    NOT NULL,
    brand            TEXT    NOT NULL,
    part_number      TEXT    NOT NULL,
    sku              TEXT    NOT NULL,
    unit_price_paise BIGINT  NOT NULL,
    quantity         INTEGER NOT NULL CHECK (quantity > 0),
    gst_rate_bps     INTEGER NOT NULL,
    hsn_code         TEXT    NOT NULL,
    line_total_paise BIGINT  NOT NULL
);
CREATE INDEX idx_order_items_fulfilment ON order_items(fulfilment_id);
CREATE INDEX idx_order_items_product ON order_items(product_id);

CREATE TABLE fulfilment_events (
    id             BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fulfilment_id  BIGINT  NOT NULL REFERENCES fulfilments(id) ON DELETE CASCADE,
    status         TEXT    NOT NULL,
    note           TEXT,
    actor_user_id  BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_fulfilment_events ON fulfilment_events(fulfilment_id);
CREATE INDEX idx_fulfilment_events_actor ON fulfilment_events(actor_user_id);

CREATE TABLE payments (
    id              BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT  NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    provider        TEXT    NOT NULL,
    intent_id       TEXT    NOT NULL UNIQUE,
    amount_paise    BIGINT  NOT NULL,
    status          TEXT    NOT NULL CHECK (status IN ('created', 'succeeded', 'failed', 'refunded')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_payments_order ON payments(order_id);

CREATE TABLE reviews (
    id            BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT  NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    user_id       BIGINT  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    rating        INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title         TEXT    NOT NULL,
    body          TEXT    NOT NULL,
    vehicle_label TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (product_id, user_id)
);
CREATE INDEX idx_reviews_product ON reviews(product_id);
CREATE INDEX idx_reviews_user ON reviews(user_id);

CREATE TABLE settings (
    key    TEXT PRIMARY KEY,
    value  TEXT NOT NULL
);

CREATE TABLE audit_log (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT  REFERENCES users(id) ON DELETE SET NULL,
    actor_role  TEXT,
    action      TEXT    NOT NULL,
    entity      TEXT    NOT NULL,
    entity_id   TEXT,
    detail      TEXT,
    ip          TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_created ON audit_log(created_at);
CREATE INDEX idx_audit_entity ON audit_log(entity, entity_id);
CREATE INDEX idx_audit_actor ON audit_log(actor_id);
